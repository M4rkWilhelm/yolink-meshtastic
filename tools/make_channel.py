#!/usr/bin/env python3
"""Write firmware/src/channel_secrets.h for the sensor's Meshtastic channel.

  make_channel.py --name YLtest                 # new random AES-256 key
  make_channel.py --name Home --psk <base64>    # key copied from the Meshtastic app

Prints the base64 key so the same channel can be added to a node in the
Meshtastic app (Channels -> add, name + PSK). Keep the generated file private.
"""
import argparse
import base64
import os
import pathlib
import sys

OUT = pathlib.Path(__file__).resolve().parent.parent / "firmware" / "src" / "channel_secrets.h"


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--name", required=True, help="channel name, max 11 characters")
    ap.add_argument("--psk", help="base64 key from the Meshtastic app (16 or 32 bytes)")
    args = ap.parse_args()

    if not 0 < len(args.name.encode()) <= 11:
        sys.exit("channel name must be 1-11 bytes (Meshtastic limit)")
    key = base64.b64decode(args.psk) if args.psk else os.urandom(32)
    if len(key) not in (16, 32):
        sys.exit(f"key must be 16 or 32 bytes, got {len(key)} (the 1-byte default keys aren't supported)")

    name_c = args.name.replace("\\", "\\\\").replace('"', '\\"')
    key_c = ", ".join(f"0x{b:02x}" for b in key)
    OUT.write_text(
        "// Generated by tools/make_channel.py. Private: do not share or commit.\n"
        "#pragma once\n\n"
        f'#define CHANNEL_NAME "{name_c}"\n'
        f"#define CHANNEL_KEY {{{key_c}}}\n"
    )
    os.chmod(OUT, 0o600)
    print(f"wrote {OUT}")
    print(f"channel name: {args.name}")
    print(f"PSK (base64): {base64.b64encode(key).decode()}")


if __name__ == "__main__":
    main()
